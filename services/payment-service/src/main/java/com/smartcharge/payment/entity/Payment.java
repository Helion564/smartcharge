package com.smartcharge.payment.entity;

import com.smartcharge.payment.enums.PaymentMethod;
import com.smartcharge.payment.enums.PaymentStatus;
import com.smartcharge.payment.enums.PaymentType;
import jakarta.persistence.*;
import lombok.*;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Represents a payment transaction in the SmartCharge platform.
 * Tracks the full lifecycle from creation to completion/failure/refund.
 */
@Entity
@Table(name = "payments", indexes = {
        @Index(name = "idx_payment_user_id", columnList = "userId"),
        @Index(name = "idx_payment_session_id", columnList = "sessionId"),
        @Index(name = "idx_payment_booking_id", columnList = "bookingId"),
        @Index(name = "idx_payment_status", columnList = "status"),
        @Index(name = "idx_payment_transaction_id", columnList = "transactionId", unique = true)
})
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
@ToString(exclude = {"gatewayTransactionId"})
public class Payment {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(updatable = false, nullable = false)
    private UUID id;

    /** ID of the user who initiated this payment. */
    @Column(nullable = false)
    private String userId;

    /** Associated charging session ID (nullable for non-session payments). */
    @Column(nullable = true)
    private String sessionId;

    /** Associated booking ID (nullable for non-booking payments). */
    @Column(nullable = true)
    private String bookingId;

    /** The category/type of this payment. */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private PaymentType paymentType;

    /** Payment method used by the user. */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private PaymentMethod paymentMethod;

    /** Current processing status of the payment. */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private PaymentStatus status;

    /** Base amount before tax (in INR). */
    @Column(nullable = false)
    private double amount;

    /** GST tax amount (18% of base amount). */
    @Column(nullable = false)
    private double taxAmount;

    /** Total amount including tax (amount + taxAmount). */
    @Column(nullable = false)
    private double totalAmount;

    /** Amount that has been refunded so far. Starts at 0. */
    @Column(nullable = false)
    @Builder.Default
    private double refundedAmount = 0.0;

    /** ISO currency code. Always INR for this platform. */
    @Column(nullable = false)
    @Builder.Default
    private String currency = "INR";

    /**
     * Internal transaction ID generated by SmartCharge.
     * Format: SC-{timestamp}-{random6chars}
     */
    @Column(nullable = false, unique = true)
    private String transactionId;

    /** Transaction reference returned by the external payment gateway. */
    @Column(nullable = true)
    private String gatewayTransactionId;

    /** Human-readable description of what this payment is for. */
    @Column(nullable = true, length = 500)
    private String description;

    /** Reason for payment failure (populated only when status = FAILED). */
    @Column(nullable = true, length = 500)
    private String failureReason;

    @CreationTimestamp
    @Column(nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @UpdateTimestamp
    @Column(nullable = false)
    private LocalDateTime updatedAt;

    /** Timestamp when payment processing completed (success or failure). */
    @Column(nullable = true)
    private LocalDateTime completedAt;
}
